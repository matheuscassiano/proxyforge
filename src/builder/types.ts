// Card builder document model. Units are millimetres from the top-left of the bleed box.
// Stored as-is in Project.designs (the Rust side treats it as opaque JSON).

export interface GradientStop {
  offset: number; // 0..1
  color: string; // #rrggbb or #rrggbbaa
}

export type Fill =
  | { kind: "none" }
  | { kind: "solid"; color: string }
  | { kind: "linear"; angle: number; stops: GradientStop[] }
  | { kind: "radial"; stops: GradientStop[] };

export interface Stroke {
  color: string;
  width: number; // mm
  dash?: number; // mm, 0 = solid
}

export interface Shadow {
  color: string;
  blur: number; // mm
  x: number; // mm
  y: number; // mm
}

export type BlendMode = "source-over" | "multiply" | "screen" | "overlay" | "soft-light" | "hard-light" | "color-dodge" | "color-burn" | "darken" | "lighten" | "difference" | "luminosity";

export interface BaseLayer {
  id: string;
  name: string;
  x: number;
  y: number;
  w: number;
  h: number;
  rotation: number; // degrees, around the layer centre
  opacity: number; // 0..1
  visible: boolean;
  locked: boolean;
  blend: BlendMode;
  shadow: Shadow | null;
  /** Set on layers generated by a TCG profile; stable across rebuilds. */
  slot?: string;
  /** Field of the TCG card this layer's text / image comes from. */
  bind?: string;
}

export interface ShapeLayer extends BaseLayer {
  kind: "rect" | "ellipse" | "polygon";
  fill: Fill;
  stroke: Stroke | null;
  radius: number; // mm, rect corners
  sides: number; // polygon: 3..12
  star: boolean; // polygon drawn as a star
}

export type ImageFit = "cover" | "contain" | "stretch";

export interface ImageFilters {
  brightness: number; // 1 = neutral
  contrast: number;
  saturate: number;
  hue: number; // degrees
  grayscale: number; // 0..1
  sepia: number; // 0..1
  blur: number; // mm
}

export interface ImageLayer extends BaseLayer {
  kind: "image";
  imageId: string | null;
  fit: ImageFit;
  zoom: number; // 1 = fitted
  offsetX: number; // -1..1, pan inside the frame
  offsetY: number;
  flipX: boolean;
  radius: number;
  stroke: Stroke | null;
  filters: ImageFilters;
  /** Alpha mask (asset id) applied to the image, e.g. a half-frame mask for hybrid frames. */
  mask?: string | null;
  /** Colour painted over the image's opaque pixels (frame recolouring, watermarks). */
  overlay?: { color: string; amount: number } | null;
}

export interface TextLayer extends BaseLayer {
  kind: "text";
  text: string; // supports **bold**, *italic*, {symbols} and new lines
  font: string;
  size: number; // pt
  weight: 400 | 700;
  italic: boolean;
  color: string;
  align: "left" | "center" | "right" | "justify";
  vAlign: "top" | "middle" | "bottom";
  lineHeight: number; // multiple of size
  letterSpacing: number; // em
  uppercase: boolean;
  autoFit: boolean; // shrink to fit the box
  stroke: Stroke | null; // outline
  background: Fill;
  padding: number; // mm
  radius: number;
  /** Second font used while the first one is not installed (e.g. pack fonts). */
  fallback?: string;
  /** Symbol set used for `{X}` codes: a TCG id ("mtg", "pokemon", "fab"). */
  symbols?: string;
  /** Symbol diameter as a fraction of the font size (default 0.92). */
  symbolScale?: number;
  /** Reminder text in parentheses: keep as typed, italicise or hide. */
  reminder?: "keep" | "italic" | "hide";
}

export type Layer = ShapeLayer | ImageLayer | TextLayer;
export type LayerKind = Layer["kind"];

export type FieldValue = string | number | boolean | null | Record<string, string>[];

/** One erase/repaint region on a real card scan, in fractions of the trim box. */
export interface RealMask {
  id: string;
  label: string;
  x: number;
  y: number;
  w: number;
  h: number;
  /** auto: average colour of the region's edge; clone: copy `sample`; keep: leave the scan. */
  fill: "auto" | "clone" | "keep" | "color";
  color?: string;
  sample?: { x: number; y: number; w: number; h: number };
}

export interface RealBase {
  imageId: string;
  sourceName: string;
  masks: RealMask[];
}

export interface TcgState {
  game: "mtg" | "pokemon" | "fab";
  cardType: string;
  fields: Record<string, FieldValue>;
  /** Per-slot edits made on the canvas (position, size, style), re-applied on every rebuild. */
  overrides: Record<string, Record<string, unknown>>;
  /** "From a real card" mode: the scan is the base and only masked regions are redrawn. */
  base?: RealBase | null;
}

export interface ProxyMark {
  position: "bottom" | "top" | "left" | "right";
  /** Clamped to 0.5–1 when drawn. */
  opacity: number;
  /** Text height in mm, clamped to at least 1.6. */
  size: number;
  /** Distance from the trim edge in mm (0.4–6); the mark always stays inside the card. */
  inset?: number;
}

export interface CardDesign {
  id: string;
  name: string;
  /** Trim size of the card. */
  width: number;
  height: number;
  /** Bleed included in the rendered image, on every side. */
  bleed: number;
  /** Inner safe margin shown as a guide. */
  safe: number;
  layers: Layer[]; // bottom → top
  /** Another design used as this card's back (double-sided proxies). */
  backId: string | null;
  updatedAt: string;
  /** Data-driven card for a supported TCG (layers with a `slot` are generated from it). */
  tcg?: TcgState | null;
  /** Placement of the mandatory "PROXY · NOT FOR SALE" mark (it cannot be turned off). */
  proxyMark?: ProxyMark;
  /** Round the trim corners on export (transparent outside). */
  roundCorners?: boolean;
}
